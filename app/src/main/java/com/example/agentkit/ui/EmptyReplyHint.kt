package com.example.agentkit.ui

/**
 * 空回复的提示文案。
 *
 * 为什么需要这个函数：模型返回 HTTP 200 但 content 为空时（供应商偶发、内容被安全策略清空、
 * 回复被截断），`ChatViewModel` 里原本的逻辑是「内容为空就不出气泡」——本意是避免中间轮
 * （只有 toolCalls、没有文本）多出一个空气泡，但对**最终轮也空**的情况同样生效。
 *
 * 结果就是**整个回合一个气泡都不产生**：用户点了发送，界面毫无变化。
 * 用户分不清是「消息没发出去」「模型抽风」还是「仍在等待」，只会反复重发——
 * 这比报错更糟，因为报错至少告诉了他发生了什么。
 *
 * 两种情形要分开说，因为用户下一步该做的事不同：
 *  - 有工具执行但没文字总结：工具已经跑完了（有副作用），用户该决定「让它继续说」还是换个问法；
 *  - 彻底空（连工具都没有）：什么都没发生，直接重试即可。
 *
 * **按钮名必须和界面上写的一致**：错误气泡上那个按钮显示的是「重试」，
 * 但空回复气泡是普通助手气泡，显示的是「重新生成」。第一版文案这里写了「重试」，
 * 真机上看到按钮叫「重新生成」，用户会去界面上找一个不存在的按钮。
 * 文案提到控件，就必须用控件上真实显示的字。
 *
 * @param hasToolMessage 本轮是否产生过工具调用（`ToolMessage`）
 */
internal fun emptyReplyHint(hasToolMessage: Boolean): String =
    if (hasToolMessage) {
        "模型执行了工具，但没有给出文字总结。可以点「重新生成」让它接着说，或换个问法。"
    } else {
        "模型返回了空内容（既没有文字也没有工具调用）。可能是模型侧异常或回复被截断，可以点「重新生成」再试一次。"
    }
