package com.example.agentkit.core.llm.local

/**
 * 轻聊档的系统提示（本地模型专用）。
 *
 * 为什么要单独写一段，而不是像以前那样截云端 [DEFAULT_SYSTEM_PROMPT] 的前三行：
 *
 * 那份提示是给**云端大模型**写的，开头几行是「你是手机操作助手，可以调用工具…」。
 * 它描述的是一个有工具、有网络、能操作界面的 Agent。而轻聊档恰恰是**没有工具**的
 * （`tools = emptyList()`，prompt 里也不带工具表）。于是模型收到一份「你什么都能做」
 * 的人设，却没有任何工具可用——它只能用训练数据里的通用助手话术把话圆回来。
 *
 * 真机 2026-10-29 15:33 的对话：
 *   用户：控制智能家居设备，这个你可以吗？
 *   模型：可以，你有支持 Alexa 或 Google Assistant 的智能音箱吗？
 *   用户：你连不了网吧，你应该不可以吧
 *   模型：我能帮你查询信息、设置闹钟、播放音乐…
 *
 * 这不是模型笨，是没人告诉它边界。3B 模型的默认人格就是「乐于助人的全能助手」，
 * 不写清楚「不能做什么」，它就一定会编。
 *
 * 所以这段提示只做三件事：说清没有联网/没有权限、给出真实能做与不能做的清单、
 * 要求不知道就说不知道。长度控制在 120 字上下（约 150 token，prefill 约 1 秒），
 * 换来的是一致的事实边界——比多算几百 token 的「礼貌寒暄」值。
 *
 * **只在轻聊档使用。** 开了 Agent 模式（有工具）时走 [LocalAgentPrompt]，
 * 那里如实告诉模型它有哪些工具，不能再说「没有权限」。
 */
object LocalChatPrompt {

    const val TEXT: String =
        "你是手机上的离线助手，没有联网，也不能操作手机或家电。\n" +
            "能做：回答问题、解释概念、写作、翻译、总结、闲聊。\n" +
            "不能做：查询天气新闻股价、设闹钟、控制设备、放音乐。\n" +
            "遇到不知道的直接说不知道，不要编。用中文简短回答。"

    /** 这段提示的特征句：日志与 QA 用它确认「边界声明确实进了 prompt」。 */
    const val MARKER = "没有联网，也不能操作手机或家电"
}
