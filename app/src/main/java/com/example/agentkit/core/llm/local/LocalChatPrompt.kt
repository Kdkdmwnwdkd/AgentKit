package com.example.agentkit.core.llm.local

/**
 * 轻聊档的系统提示（本地模型专用）。
 *
 * 为什么需要单独一段：云端那份 [DEFAULT_SYSTEM_PROMPT] 开头是「你是手机操作助手，可以调用
 * 工具、可以操作界面」，描述的是一个有工具、有网络、有权限的 Agent。轻聊档恰恰没有工具
 * （`tools = emptyList()`），模型拿着「什么都行」的人设却无手可用，只能用训练数据里的
 * 通用助手话术把话圆回来——真机 2026-10-29 15:33 就是这么答出「可以控制智能家居，
 * 你有 Alexa 吗」的。
 *
 * 但**边界不能写成禁令清单**。1.475 那一版是：
 *
 *   ```
 *   能做：回答问题、解释概念、写作、翻译、总结、闲聊。
 *   不能做：查询天气新闻股价、设闹钟、控制设备、放音乐。
 *   ```
 *
 * 真机读起来很别扭：用户问「你能干嘛呢」，它把这张表原样念一遍；再追问「能解释什么概念、
 * 翻译什么」，它就掉进「数学物理概念、文学艺术知识、多种语言互译」的模板腔——因为提示里
 * 给它的是一份**能力清单**，不是一个**说话的人**。参考 IRIDIS（默认几乎不写 system prompt，
 * 3B 自己的语气反而更自然）之后改成现在这样：
 *
 *  - 边界只留一句，写成因果（「没有联网、没有系统权限 → 所以查不到、做不到」），
 *    不罗列禁止项，模型就不必在每轮回答里复述它；
 *  - 加两条语气约束（两三句讲完、别用「包括但不限于」这类模板话），
 *    这既治「傻」，也顺带把输出压短——83 token 的回答要 8.6 秒，少一半就省 4 秒。
 *
 * 长度约 100 字（约 90 token）。**只在轻聊档使用**；开了 Agent 模式（有工具）走
 * [LocalAgentPrompt]，那里如实告诉模型它有哪些工具。
 */
object LocalChatPrompt {

    const val TEXT: String =
        "你是北辰，一个跑在这台手机上的离线小模型。你没有联网，也没有系统权限，" +
            "实时信息查不到，家电和别的 App 也操作不了——遇到这类请求直接说做不到，别编。\n" +
            "说话像人：两三句讲完，不要「包括但不限于」这种模板腔；拿不准就说拿不准。"

    /** 这段提示的特征句：日志与 QA 用它确认「本地能力声明确实进了 prompt」。 */
    const val MARKER = "跑在这台手机上的离线小模型"
}
